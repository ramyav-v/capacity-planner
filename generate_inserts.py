def main():
    inserts = []
    skipped = []

    for project_name, emp_name, alloc_str in DATA:
        emp_id = EMPLOYEES.get(emp_name)
        proj_id = PROJECTS.get(project_name)

        if not emp_id:
            skipped.append(f"-- SKIPPED: Employee '{emp_name}' not found in employee table (project: {project_name})")
            continue
        if not proj_id:
            skipped.append(f"-- SKIPPED: Project '{project_name}' not found in project table (employee: {emp_name})")
            continue

        values = alloc_str.split(',')
        for i, val in enumerate(values):
            val = val.strip()
            if not val:
                continue
            try:
                alloc = float(val)
            except ValueError:
                continue
            if alloc == 0:
                continue
            if i >= len(DATES):
                break
            date = DATES[i]
            inserts.append(
                f"INSERT INTO weekly_allocation (employee_id, project_id, week_start_date, allocation_pct) "
                f"VALUES ({emp_id}, {proj_id}, '{date}', {alloc});"
            )

    with open('weekly_allocation_inserts.sql', 'w') as f:
        f.write("-- Auto-generated weekly_allocation INSERT statements\n")
        f.write("-- Generated from CSV data\n\n")
        if skipped:
            f.write("-- ========== SKIPPED ENTRIES ==========\n")
            for s in sorted(set(skipped)):
                f.write(s + "\n")
            f.write("\n")
        f.write(f"-- ========== {len(inserts)} INSERT STATEMENTS ==========\n\n")
        for ins in inserts:
            f.write(ins + "\n")

    print(f"Generated {len(inserts)} INSERT statements")
    print(f"Skipped entries: {len(set(skipped))}")
    for s in sorted(set(skipped)):
        print(s)

if __name__ == '__main__':
    main()
